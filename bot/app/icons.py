"""Иконки бота: премиум-эмодзи на кнопках и в тексте.

У Telegram два разных механизма, и путать их нельзя:

* на кнопке — поле ``icon_custom_emoji_id``. HTML в тексте кнопки не
  работает вообще, поэтому только так;
* в тексте сообщения — тег ``<tg-emoji emoji-id="…">символ</tg-emoji>``.
  Символ-заглушка обязан совпадать с эмодзи, которым набор описывает этот
  id, иначе Telegram отвергает всё сообщение целиком (ENTITY_TEXT_INVALID).

Поэтому у каждой иконки хранится и запасной юникод-символ для обычного
режима, и точная заглушка набора. Заглушки не выдуманы: они получены у
Telegram методом getCustomEmojiStickers для этих самых id.

Проверено на живом API: допустимых стилей кнопок ровно три — primary,
success и danger. Любое другое значение («secondary» в том числе) Telegram
отклоняет вместе со всем сообщением, поэтому ALLOWED_STYLES — белый список.
"""

from dataclasses import dataclass
from typing import Final

STYLE_PRIMARY: Final = "primary"
STYLE_SUCCESS: Final = "success"
STYLE_DANGER: Final = "danger"
ALLOWED_STYLES: Final = frozenset({STYLE_PRIMARY, STYLE_SUCCESS, STYLE_DANGER})


@dataclass(frozen=True, slots=True)
class Icon:
    plain: str
    """Обычный юникод — режим без премиума и запасной вариант."""
    emoji_id: str | None = None
    """id премиум-эмодзи."""
    premium_char: str | None = None
    """Символ, которым набор описывает этот id. Обязан совпадать точно."""

    @property
    def placeholder(self) -> str:
        return self.premium_char or self.plain


